"""Export editable-source Phase B module examples (metres, Y-up) as GLB.

These are INTERCHANGE SAMPLES, not an alternative set of salvageable gameplay
actors; live Brinewick is generated by the separate canonical Godot scripts.
Run: python tools/generate_phase_b_reference_glb.py
Dependencies: numpy, trimesh; deterministic. Does not modify the game catalogue.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
import trimesh

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'art'/'reference_exports'


def prism(outline: list[tuple[float,float]], y0: float, y1: float, rgb: tuple[int,int,int]) -> trimesh.Trimesh:
    """Convex extruded irregular block with triangulated flat top and bottom."""
    n=len(outline)
    verts=np.array([[x,y0,z] for x,z in outline]+[[x,y1,z] for x,z in outline],dtype=float)
    faces=[]
    for i in range(1,n-1):
        faces.append([0,i+1,i]);faces.append([n,n+i,n+i+1])
    for i in range(n):
        j=(i+1)%n
        faces.extend(([i,j,n+j],[i,n+j,n+i]))
    m=trimesh.Trimesh(vertices=verts,faces=np.array(faces,dtype=np.int64),process=True)
    m.visual.face_colors=np.tile(np.array((*rgb,255),dtype=np.uint8),(len(m.faces),1))
    return m


def make() -> trimesh.Scene:
    scene=trimesh.Scene()
    grey=(119,117,105)
    oak=(103,80,59)
    slate=(76,84,85)
    stone=prism([(-.47,-.31),(.15,-.34),(.48,-.22),(.54,.15),(.20,.35),(-.38,.27),(-.52,.03)],-.2,.22,grey)
    scene.add_geometry(stone,geom_name='IrregularFacetedFoundationStone',node_name='STONE_01')
    timber=prism([(-.16,-.13),(-.12,-.17),(.13,-.16),(.18,-.11),(.17,.12),(.11,.17),(-.13,.15),(-.18,.10)],-.95,.95,oak)
    timber.apply_translation([1.5,0,0])
    scene.add_geometry(timber,geom_name='ChamferedHewnOakPost',node_name='TIMBER_01')
    # Separate thin overlapping slate units. Surface edges vary visibly and
    # are deliberately geometry, not textured-on shingle linework.
    for idx in range(3):
        x=3.1+float(idx%2)*0.36
        z=float(idx)*0.42
        tile=prism([(-.22,-.30),(.18,-.31),(.23,-.20),(.22,.25),(-.19,.28)],0.0,0.045,slate)
        tile.apply_translation([x,float(idx%2)*0.018,z])
        scene.add_geometry(tile,geom_name='ShapedOverlappedSlate_%02d'%idx,
                           node_name='SLATE_%02d'%idx)
    scene.units='m'
    return scene


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    scene=make()
    path=OUT/'hollowmere_phase_b_surface_modules_reference.glb'
    path.write_bytes(scene.export(file_type='glb'))
    loaded=trimesh.load(path,force='scene')
    if len(loaded.geometry)!=5 or any(len(g.vertices)<6 for g in loaded.geometry.values()):
        raise RuntimeError('Roundtrip sample GLB lost component geometry')
    manifest={'format':'glTF 2.0 GLB','role':'Supplemental offline preview, not gameplay import',
              'base_source_sha':'3f605237ee3d016c36689f5b58cafd4473203d08',
              'node_count':len(loaded.graph.nodes_geometry),'meshes':list(loaded.geometry),
              'unit':'metre','up':'Y','editable_generator':'tools/generate_phase_b_reference_glb.py'}
    (OUT/'phase_b_reference_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('GLB roundtrip passed:',len(loaded.geometry),'named reusable samples; not in-engine verified')

if __name__=='__main__':
    main()
